#!/usr/bin/env Rscript

# Generate figures/scripts/FIGURE_INDEX.md: which file in figures/ a reader
# should run for each published figure, which one draws its panels, and what
# every other file in figures/ is for.
#
# figures/ is laid out by purpose (2026-10-20): main/ and extended_data/ hold the
# published figures, scripts/ what draws and assembles them, candidates/ the
# exploratory renderers, audits/ the checks and reports on the rendered layer,
# contracts/ the figure contracts and annotation maps.
#
# Authority: provenance/publication_registry/figure_canonical_generation_registry.csv
# (figure_id, canonical_generation, canonical_renderer, manuscript_entry_point)
# and canonical_publication_registry.csv for the Extended Data identities.
# This tool only reformats those records; it never decides which is canonical.

source(file.path("R", "paths.R"))

gen_registry <- utils::read.csv(
  repo_path("provenance/publication_registry/figure_canonical_generation_registry.csv"),
  stringsAsFactors = FALSE)
pub_registry <- utils::read.csv(
  repo_path("provenance/publication_registry/canonical_publication_registry.csv"),
  stringsAsFactors = FALSE)

FOLDERS <- c(scripts = "renders or assembles a published figure",
             candidates = "candidate or exploratory renderer (not published)",
             audits = "audit or report on the rendered layer")
files <- unlist(lapply(names(FOLDERS), function(d)
  file.path("figures", d, sort(list.files(repo_path("figures", d), pattern = "[.]R$")))))
contracts <- file.path("figures", "contracts", sort(list.files(repo_path("figures", "contracts"))))

entry_points <- c(gen_registry$manuscript_entry_point)
renderers <- unique(c(gen_registry$canonical_renderer, pub_registry$canonical_renderer))
idx <- data.frame(
  file = files,
  role = vapply(files, function(f) {
    if (f %in% entry_points) "manuscript entry point (assembles)"
    else if (f %in% renderers) "draws the panels of a published figure"
    else unname(FOLDERS[[basename(dirname(f))]])
  }, ""),
  stringsAsFactors = FALSE, row.names = NULL)

L <- c(
  "# Figure index",
  "",
  "Generated by `tools/generate_figure_index.R`. Do not hand-edit.",
  "",
  "## Published figures",
  "",
  "| Figure | Entry point | Canonical generation | Canonical renderer | Panels |",
  "| --- | --- | --- | --- | --- |")
for (i in seq_len(nrow(gen_registry))) {
  g <- gen_registry[i, ]
  L <- c(L, sprintf("| %s | `%s` | %s | `%s` | %s |",
                    g$figure_id, g$manuscript_entry_point,
                    g$canonical_generation, g$canonical_renderer, g$panels))
}
L <- c(L, "",
  paste("The **entry point** is what you run: it selects and validates the",
        "promoted artefact and assembles the figure. The **canonical",
        "renderer** is what produced the panels. They are different files on",
        "purpose; do not run a renderer expecting an assembled figure."),
  "")

ed <- pub_registry[grepl("^extended_data", pub_registry$publication_id), ]
if (nrow(ed)) {
  L <- c(L, "## Extended Data", "",
    "| Identity | Renderer | Status |", "| --- | --- | --- |")
  for (i in seq_len(nrow(ed))) {
    L <- c(L, sprintf("| %s | `%s` | %s |", ed$publication_id[i],
                      ed$canonical_renderer[i], ed$status[i]))
  }
  L <- c(L, "")
}

L <- c(L, "## Every script in `figures/`", "", "| File | Role |", "| --- | --- |",
       sprintf("| `%s` | %s |", idx$file, idx$role), "",
       "## Contracts and annotation maps", "",
       paste0("- `", contracts, "`"), "")

writeLines(L, repo_path("figures", "scripts", "FIGURE_INDEX.md"), useBytes = TRUE)
utils::write.csv(idx, repo_path("figures", "scripts", "figure_index.csv"), row.names = FALSE)

cat("wrote figures/scripts/FIGURE_INDEX.md and figures/scripts/figure_index.csv\n")
